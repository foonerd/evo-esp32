//! # evo-esp32-catalogue
//!
//! The catalogue is data a distribution writes and the firmware's build
//! resolves. This crate is the resolver: it reads `catalogue.toml`,
//! validates it with the SDK's rules, checks that the plugins a firmware
//! links stock every shelf (and nothing the catalogue does not declare),
//! and emits the catalogue as Rust so the device carries a table, not a
//! TOML parser.
//!
//! Used two ways: as a library from a firmware crate's `build.rs`, and as
//! the `evo-esp32-catalogue` binary for a look at a catalogue by hand.
//! Host-only; nothing here runs on the device.

use std::fmt::Write as _;
use std::path::Path;

use evo_esp32_sdk::catalogue::{Catalogue, CatalogueError, ShelfRef};
use evo_esp32_sdk::plugin::PluginDescription;
pub use evo_esp32_steward::AdmissionError;

/// Why a catalogue file could not be used.
#[derive(Debug)]
pub enum Error {
    /// The file could not be read.
    Io(std::io::Error),
    /// The TOML did not parse into a catalogue.
    Parse(String),
    /// The catalogue parsed but is not well formed.
    Invalid(CatalogueError),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Io(e) => write!(f, "reading catalogue: {e}"),
            Self::Parse(e) => write!(f, "parsing catalogue: {e}"),
            Self::Invalid(e) => write!(f, "catalogue is not well formed: {e}"),
        }
    }
}

impl std::error::Error for Error {}

/// Parse and validate a catalogue from TOML text.
pub fn parse(text: &str) -> Result<Catalogue, Error> {
    let c: Catalogue =
        toml::from_str(text).map_err(|e| Error::Parse(e.to_string()))?;
    c.validate().map_err(Error::Invalid)?;
    Ok(c)
}

/// Parse and validate a catalogue from a file.
pub fn load(path: impl AsRef<Path>) -> Result<Catalogue, Error> {
    let text = std::fs::read_to_string(path).map_err(Error::Io)?;
    parse(&text)
}

/// What a stocking check found.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Report {
    /// Shelves the catalogue declares that no plugin stocks.
    pub unstocked: Vec<ShelfRef>,
    /// Plugins the steward would refuse, and why.
    pub refused: Vec<AdmissionError>,
}

impl Report {
    /// True when every shelf is stocked and every plugin would be admitted.
    pub fn is_clean(&self) -> bool {
        self.unstocked.is_empty() && self.refused.is_empty()
    }
}

impl std::fmt::Display for Report {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        for s in &self.unstocked {
            writeln!(f, "unstocked: {s}")?;
        }
        for r in &self.refused {
            writeln!(f, "refused: {r}")?;
        }
        if self.is_clean() {
            writeln!(f, "clean")?;
        }
        Ok(())
    }
}

/// Check that `plugins` stock `catalogue`: every plugin would be admitted,
/// and every shelf has at least one plugin.
pub fn check(catalogue: &Catalogue, plugins: &[PluginDescription]) -> Report {
    let mut report = Report::default();
    let mut admitted: Vec<&'static str> = Vec::new();
    for p in plugins {
        match evo_esp32_steward::admission_check(catalogue, &admitted, p) {
            Ok(()) => admitted.push(p.name),
            Err(e) => report.refused.push(e),
        }
    }
    for rack in &catalogue.racks {
        for shelf in &rack.shelves {
            let stocked = plugins.iter().any(|p| {
                p.stocks
                    .iter()
                    .any(|s| s.rack == rack.name && s.shelf == shelf.name)
            });
            if !stocked {
                report
                    .unstocked
                    .push(ShelfRef::new(rack.name.clone(), shelf.name.clone()));
            }
        }
    }
    report
}

/// The catalogue as Rust: a function `pub fn catalogue() -> Catalogue`
/// building it from literals, for a firmware to include at build time.
pub fn emit_rust(catalogue: &Catalogue) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// Generated by evo-esp32-catalogue. Do not edit.");
    let _ = writeln!(out, "use evo_esp32_sdk::catalogue::*;");
    let _ = writeln!(out, "/// The catalogue this firmware was built with.");
    let _ = writeln!(out, "pub fn catalogue() -> Catalogue {{");
    let _ = writeln!(out, "    Catalogue {{ racks: alloc::vec![");
    for r in &catalogue.racks {
        let _ = writeln!(out, "        Rack {{");
        let _ = writeln!(out, "            name: {}.into(),", lit(&r.name));
        let _ = writeln!(out, "            family: Family::{:?},", r.family);
        let kinds: Vec<String> =
            r.kinds.iter().map(|k| format!("Kind::{k:?}")).collect();
        let _ = writeln!(
            out,
            "            kinds: alloc::vec![{}],",
            kinds.join(", ")
        );
        let _ =
            writeln!(out, "            charter: {}.into(),", lit(&r.charter));
        let _ = writeln!(out, "            shelves: alloc::vec![");
        for s in &r.shelves {
            let _ = writeln!(
                out,
                "                Shelf {{ name: {}.into(), shape: {}, description: {}.into() }},",
                lit(&s.name),
                s.shape,
                lit(&s.description)
            );
        }
        let _ = writeln!(out, "            ],");
        let _ = writeln!(out, "        }},");
    }
    let _ = writeln!(out, "    ] }}");
    let _ = writeln!(out, "}}");
    out
}

/// Read `from`, validate, and write the Rust form to `to`. For `build.rs`.
pub fn emit_file(
    from: impl AsRef<Path>,
    to: impl AsRef<Path>,
) -> Result<Catalogue, Error> {
    let c = load(from)?;
    std::fs::write(to, emit_rust(&c)).map_err(Error::Io)?;
    Ok(c)
}

fn lit(s: &str) -> String {
    format!("{s:?}")
}

#[cfg(test)]
mod tests {
    use super::*;
    use evo_esp32_sdk::plugin::{InstanceShape, InteractionShape, Stocking};

    const EXAMPLE: &str = r#"
[[racks]]
name = "example"
family = "domain"
kinds = ["registrar"]
charter = "Minimal example rack."

[[racks.shelves]]
name = "echo"
shape = 1
description = "Echoes inputs back."
"#;

    static ECHO: [Stocking; 1] = [Stocking {
        rack: "example",
        shelf: "echo",
        shape: 1,
    }];

    fn echo() -> PluginDescription {
        PluginDescription {
            name: "org.evoframework.example.echo",
            version: "0.1.0",
            instance: InstanceShape::Singleton,
            interaction: InteractionShape::Respondent,
            stocks: &ECHO,
        }
    }

    #[test]
    fn evo_cores_minimal_example_parses() {
        let c = parse(EXAMPLE).unwrap();
        assert_eq!(c.racks[0].shelves[0].shape, 1);
        assert_eq!(c.racks[0].charter, "Minimal example rack.");
    }

    #[test]
    fn malformed_toml_and_catalogues_are_refused() {
        assert!(matches!(parse("racks = 1"), Err(Error::Parse(_))));
        let dup = format!("{EXAMPLE}\n{EXAMPLE}");
        assert!(matches!(parse(&dup), Err(Error::Invalid(_))));
    }

    #[test]
    fn a_stocked_catalogue_is_clean_and_an_unstocked_one_is_not() {
        let c = parse(EXAMPLE).unwrap();
        assert!(check(&c, &[echo()]).is_clean());
        let r = check(&c, &[]);
        assert_eq!(r.unstocked, vec![ShelfRef::new("example", "echo")]);
        let mut wrong = echo();
        static WRONG: [Stocking; 1] = [Stocking {
            rack: "example",
            shelf: "echo",
            shape: 2,
        }];
        wrong.stocks = &WRONG;
        let r = check(&c, &[wrong]);
        assert!(matches!(r.refused[0], AdmissionError::ShapeMismatch { .. }));
        assert!(!r.is_clean());
    }

    #[test]
    fn emitted_rust_names_every_literal() {
        let c = parse(EXAMPLE).unwrap();
        let rs = emit_rust(&c);
        assert!(rs.contains("pub fn catalogue() -> Catalogue"));
        assert!(rs.contains(r#"name: "example".into()"#));
        assert!(rs.contains("family: Family::Domain"));
        assert!(rs.contains("kinds: alloc::vec![Kind::Registrar]"));
        assert!(rs.contains(r#"Shelf { name: "echo".into(), shape: 1, description: "Echoes inputs back.".into() }"#));
    }
}
